"""Generate MARSWALK_AI_CAPABILITY_REGISTRY.md from the code (so the document cannot drift from the registry).

Usage:  .venv\\Scripts\\python scripts\\export_capabilities.py
It registers every adapter variant (standalone, frontend, Science Engine, Marswalk backend) without contacting any server.
"""
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from marswalk_ai.adapters import marswalk_http, science_engine  # noqa: E402
from marswalk_ai.config import Settings  # noqa: E402
from marswalk_ai.main import build_app_state  # noqa: E402
from marswalk_ai.registry import CapabilityRegistry  # noqa: E402

DEMO_UI = {"client": "marswalk-ai-demo", "capabilities": [], "sections": [{"id": "dashboard", "label": "Mission dashboard"}, {"id": "map", "label": "Main map"}],
           "layers": [{"id": "mola", "label": "MOLA shaded elevation"}, {"id": "hirise", "label": "HiRISE orthomosaic"}]}

INTRO = """# Marswalk AI: Capability Registry

> Generated by `scripts/export_capabilities.py` from the registry code. Do not edit by hand.

The Capability Registry (`backend/marswalk_ai/registry.py`) is the **allowlist** of everything the assistant can do. The LLM and the
rule planner can only call registered capabilities, and every call goes through the same pipeline:

1. **Lookup.** Unknown ids are `rejected` (`unknown_capability`).
2. **Availability.** `unavailable` capabilities return the reason; frontend capabilities need a connected UI that advertised them.
3. **Validation.** Arguments must match the closed JSON schema (`additionalProperties: false`); otherwise they are `rejected` and **not executed**.
4. **Permission.** `read` and `write` run; `confirm` returns `pending_confirmation` and runs only after `POST /api/assistant/confirm`.
5. **Execution.** The handler runs with a timeout. Exceptions become typed errors; nothing crashes the conversation.
6. **Result.** Output is soft-checked against the output schema; provenance (`provider`, `data_mode`) is attached; evidence and limitations are collected.

## Fields

| Field | Meaning |
| --- | --- |
| `id` | Stable identifier (`area.verb`). LLM tool name = id with `.` → `__` |
| `side` | `backend` (runs in Python) or `frontend` (emits a typed action the UI executes and acknowledges) |
| `permission` | `read` · `write` (changes UI/session state) · `confirm` (needs explicit user approval) |
| `changes_state` | Whether the capability changes application or persistent state |
| `availability` | `available` · `degraded` · `unavailable` (+ reason) |
| `provider` | Adapter implementing it: `standalone`, `frontend`, `science-engine`, `marswalk-backend` |
| `data_mode` | `real` (measured / DEM) · `simulated` · `calculated` (model) · `reference` (transferred reference value) · `cached-sample` · `mixed` · `n/a` |
| `priority` | When several adapters register the same id, the highest priority wins: Marswalk backend 30 > Science Engine 20 > standalone 10 > local fallback 5 > unavailable stub 1 |
| `error_policy` | Failures are reported to the user with the operation name; never replaced by invented values |

## Dynamic registration

* Adapters call `registry.register(Capability(...))` at startup for what they **actually** support. `science_engine` registers only if
  `/api/health` answers; `marswalk_http` registers only enabled or probed endpoints.
* Frontend capabilities are offered per session, only if the UI listed them in its handshake. `map.change_layer` and
  `navigation.open_section` build their enums from the layers and sections that UI reported.
* Nothing is auto-discovered from source code. OpenAPI specs may be used to write adapters, but each capability is registered explicitly.
* `registry.unregister(id, provider)` removes a capability at runtime; the core never changes.
"""


def fmt_schema(schema: dict) -> str:
    return "```json\n" + json.dumps(schema, indent=1, ensure_ascii=False) + "\n```"


async def main():
    s = Settings.from_env()
    s.session_db = ":memory:"
    s.llm_provider = "offline"
    services, reg, _ = await build_app_state(s)
    session = services.store.create(DEMO_UI)

    variants = {}
    eng = CapabilityRegistry()
    science_engine.register(eng, services)
    mw = CapabilityRegistry()
    marswalk_http.register(mw, services, ["elevation", "route_auto", "route_analyze", "eva", "spaceweather", "meda", "records"])

    lines = [INTRO, "## Summary\n",
             "| id | side | permission | standalone provider | Science Engine | Marswalk backend | data_mode | availability (standalone) |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for c in reg.all():
        lines.append(f"| `{c.id}` | {c.side} | {c.permission} | {c.provider} (p{c.priority}) | "
                     f"{'✔ p20' if eng.get(c.id) else '–'} | {'✔ p30' if mw.get(c.id) else '–'} | {c.data_mode} | "
                     f"{c.availability}{' — ' + c.availability_reason if c.availability_reason else ''} |")
    lines.append("\nState of this build: terrain = " + services.terrain.data_mode + f" ({', '.join(d['id'] for d in services.terrain.describe())}); "
                 f"documents = {services.status['knowledge']['documents']}. Standalone `environment.analyze` and `space_weather.analyze` are "
                 "unavailable stubs until the Science Engine or Marswalk backend registers them.\n")

    for title, side in (("Backend capabilities", "backend"), ("Frontend capabilities", "frontend")):
        lines.append(f"## {title}\n")
        for c in [x for x in reg.all() if x.side == side]:
            d = c.describe(session)
            lines.append(f"### `{c.id}` · {c.name}\n")
            lines.append(c.description + "\n")
            lines.append(f"* side **{c.side}** · category `{c.category}` · permission **{c.permission}** · changes_state {c.changes_state} · "
                         f"timeout {c.timeout_s:g} s")
            lines.append(f"* provider `{c.provider}` (priority {c.priority}) · data_mode `{c.data_mode}` · availability `{c.availability}`"
                         + (f" ({c.availability_reason})" if c.availability_reason else ""))
            others = [f"`{r.get(c.id).provider}` (p{r.get(c.id).priority}, {r.get(c.id).data_mode})" for r in (eng, mw) if r.get(c.id)]
            if others:
                lines.append("* also implemented by: " + ", ".join(others))
            if c.notes:
                lines.append(f"* notes: {c.notes}")
            for r in (eng, mw):
                if r.get(c.id) and r.get(c.id).notes:
                    lines.append(f"* {r.get(c.id).provider}: {r.get(c.id).notes}")
            lines.append("\nInput schema" + (" (enums shown for the demo UI; built per session)" if c.schema_builder else "") + ":\n")
            lines.append(fmt_schema(d["input_schema"]))
            if c.output_schema:
                lines.append("\nOutput schema (soft contract; extra fields allowed):\n")
                lines.append(fmt_schema(c.output_schema))
            lines.append("")
    lines.append("""## Frontend action payloads

Frontend capabilities return `{"action_id", "type", "status": "pending_ack"}` to the assistant and add an entry to `frontend_actions`.
The payload types are listed in [MARSWALK_AI_INTEGRATION_GUIDE.md §4](MARSWALK_AI_INTEGRATION_GUIDE.md#4-frontend-action-contract).

| capability | action `type` |
| --- | --- |
| `map.display_route` | `display_route` |
| `map.highlight_location` | `highlight_location` |
| `map.zoom_to_location` | `zoom_to_location` |
| `map.change_layer` | `change_layer` |
| `map.clear_route` | `clear_route` |
| `navigation.open_section` | `navigate_to_section` |
""")
    (ROOT / "MARSWALK_AI_CAPABILITY_REGISTRY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote MARSWALK_AI_CAPABILITY_REGISTRY.md ({len(reg.all())} capabilities)")
    await services.http.aclose()


if __name__ == "__main__":
    asyncio.run(main())
